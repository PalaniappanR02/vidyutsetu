"""## STEP 4: Feature Engineering Pipeline
We design a custom, production-safe sklearn-compatible Preprocessor. This parses the timestamps dynamically, flags data type anomalies, checks ranges, calculates sequential differences, and returns standard numeric features without data leakage.
"""

class AMIPayloadPreprocessor(BaseEstimator, TransformerMixin):
    def __init__(self):
        pass

    def fit(self, X, y=None):
        return self

    def transform(self, X):
        # Keep raw source dataframe unmodified
        X_df = pd.DataFrame(X).copy()

        # 1. Null counting features
        X_df["null_count"] = X_df.isnull().sum(axis=1)

        # 2. Safe parsing of types and bounds checks
        # Construct target columns with numeric converters while coercing errors gracefully
        X_df["voltage_clean"] = pd.to_numeric(X_df["voltage"], errors='coerce')
        X_df["kwh_clean"] = pd.to_numeric(X_df["kwh"], errors='coerce')
        X_df["frequency_clean"] = pd.to_numeric(X_df["frequency"], errors='coerce')
        X_df["current_clean"] = pd.to_numeric(X_df["current"], errors='coerce')
        X_df["pf_clean"] = pd.to_numeric(X_df["power_factor"], errors='coerce')

        # 3. Create boolean indicators for parsing/datatype faults
        X_df["is_voltage_malformed"] = X_df["voltage"].apply(lambda x: 1 if isinstance(x, str) and not x.replace('.','',1).isdigit() else 0)
        X_df["is_freq_out_of_range"] = X_df["frequency_clean"].apply(lambda x: 1 if (pd.notnull(x) and (x < 45.0 or x > 55.0)) else 0)
        X_df["is_kwh_negative"] = X_df["kwh_clean"].apply(lambda x: 1 if (pd.notnull(x) and x < 0) else 0)

        # 4. Fill values safely for modeling input
        X_df["voltage_clean"] = X_df["voltage_clean"].fillna(230.0)
        X_df["kwh_clean"] = X_df["kwh_clean"].fillna(0.0)
        X_df["frequency_clean"] = X_df["frequency_clean"].fillna(50.0)
        X_df["current_clean"] = X_df["current_clean"].fillna(0.0)
        X_df["pf_clean"] = X_df["pf_clean"].fillna(0.95)
        X_df["payload_size_bytes"] = pd.to_numeric(X_df["payload_size_bytes"], errors='coerce').fillna(250.0)

        # Extract structured feature array
        feature_cols = [
            "null_count", "voltage_clean", "kwh_clean", "frequency_clean",
            "current_clean", "pf_clean", "payload_size_bytes",
            "is_voltage_malformed", "is_freq_out_of_range", "is_kwh_negative"
        ]
        return X_df[feature_cols].values

print("Preprocessor Pipeline compiled successfully!")

